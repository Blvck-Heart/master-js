// DATA TYPES IN JAVASCRIPT

// Data types in JavaScript define what kind of values a variable can hold and how those values behave in a program. 
// They determine how data is stored in a memory and how operations like comparisons, calculations and conversions work.

// DATA TYPE CATEGORIES
// 1. Primitive data type
// 2. Non-primitive data type

// PRIMITIVE DATA TYPES
// Primitive data types represent individual values.
// There are 7 types of primitive data types which are further separated into numeric and non-numeric type.
// The numeric types are namely:
// 1. Number
// 2. Bigint

// The non-numeric are namely;
// 1. String
// 2. Boolean
// 3. Null
// 4. Undefined
// 5. Symbol

// NON-PRIMITIVE DATA TYPES
// Non-primitive values are used to represent more complex structures.
// The data type under non-primitive are:
// 1. Object
// 2. Array
// 3. Function
// 4. Date object
// 5. Regular Expression


//DIFFERENCE BETWEEN UNDEFINED AND NULL

// Undefined indicates that variable has been declared but not yet assigned a value, whereas null is a value that represents the deliberate absence of any value

